import { expect, test } from '@playwright/test'

test('abre o cadastro público', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('heading', { name: /Quem acolhe/ })).toBeVisible()
  await page.getByRole('button', { name: /Iniciar meu cadastro/ }).click()
  await expect(page.getByRole('heading', { name: 'Identificação' })).toBeVisible()
  await expect(page.getByText('Etapa 1 de 4')).toBeVisible()
})

